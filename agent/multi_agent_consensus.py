class MultiAgentConsensusOrchestrator:
    """Panel coordinator managing Planner -> Executor -> Critic consensus loops."""

    def __init__(
        self,
        tools: Optional[ToolRegistry] = None,
        max_debate_rounds: int = 3,
    ) -> None:
        self.max_debate_rounds: int = max(1, min(max_debate_rounds, 5))
        self.planner = PlannerAgent()
        self.executor = ExecutorAgent(tools=tools)
        self.critic = CriticAgent()

    def run_consensus(self, goal: str) -> ConsensusResult:
        """Execute collaborative debate until consensus or max rounds reached."""
        t0 = time.perf_counter()
        logger.info("Initiating Multi-Agent Consensus panel for goal: '%s'", goal)

        debate_history: List[DebateRound] = []
        current_feedback: Optional[List[str]] = None
        final_answer = ""
        is_approved = False

        plan = self.planner.plan(goal)

        for round_idx in range(1, self.max_debate_rounds + 1):
            round_start = time.perf_counter()
            logger.info("=== Consensus Debate Round #%d ===", round_idx)

            # 1. Executor executes plan and synthesizes draft
            draft_synthesis, observations = self.executor.execute(
                plan=plan,
                critic_feedback=current_feedback,
            )

            # 2. Critic audits the synthesis and tool observations
            review = self.critic.audit(
                goal=goal,
                synthesis=draft_synthesis,
                observations=observations,
                round_number=round_idx,
            )

            round_duration = time.perf_counter() - round_start
            debate_round = DebateRound(
                round_number=round_idx,
                plan=plan,
                executor_synthesis=draft_synthesis,
                tool_observations=observations,
                critic_review=review,
                duration_seconds=round_duration,
            )
            debate_history.append(debate_round)

            final_answer = draft_synthesis

            if review.approved:
                logger.info("Consensus achieved in Round #%d (Score: %.1f%%)!",
                            round_idx, review.groundedness_score)
                is_approved = True
                break
            else:
                logger.info("Critic requested revisions in Round #%d (%d objections).",
                            round_idx, len(review.objections))
                current_feedback = review.suggested_revisions

        total_latency = time.perf_counter() - t0

        # Audit consensus session and granular steps into MySQL
        try:
            mysql_mgr = get_mysql_manager()
            session_id = f"consensus_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}_{uuid.uuid4().hex[:6]}"
            steps_data = []
            for r in debate_history:
                for obs in r.tool_observations:
                    steps_data.append({
                        "step_index": obs.get("step_id", 1),
                        "thought_trace": f"Debate Round {r.round_number} plan: {r.plan.strategy}",
                        "action_name": obs.get("tool", "internal"),
                        "action_input": obs.get("input", {}),
                        "observation_output": str(obs.get("output", ""))[:500],
                        "step_latency": round(r.duration_seconds / max(1, len(r.tool_observations)), 3),
                    })
            session_data = {
                "session_id": session_id,
                "input_objective": goal,
                "success": is_approved,
                "total_steps": len(steps_data),
                "retry_count": max(0, len(debate_history) - 1),
                "execution_latency": round(total_latency, 3),
            }
            mysql_mgr.record_agent_session(session_data, steps_data)
            logger.info("Audited consensus session '%s' with %d steps to MySQL.", session_id, len(steps_data))
        except Exception as exc:
            logger.debug("Could not audit consensus session to MySQL: %s", exc)

        return ConsensusResult(
            goal=goal,
            final_answer=final_answer,
            consensus_approved=is_approved,
            total_rounds=len(debate_history),
            debate_history=debate_history,
            total_latency_seconds=total_latency,
        )


