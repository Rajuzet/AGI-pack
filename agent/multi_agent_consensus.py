"""Multi-Agent Consensus, Debate, and Peer-Verification Engine.

Collaborative multi-agent reasoning panel comprised of:
1. Planner Agent: Deconstructs complex objectives into an ordered execution plan.
2. Executor Agent: Interacts with the sandboxed toolchain to gather empirical observations.
3. Critic / Auditor Agent: Validates math, verifies groundedness against FAISS vector
   memory, detects hallucinations, and enforces peer consensus.

Debate Protocol:
Orchestrates up to 3 rounds of peer review. Concludes when the Critic provides
consensus approval or the maximum round threshold is reached.
"""

