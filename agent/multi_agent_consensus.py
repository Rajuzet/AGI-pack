# ===========================================================================
# Data Models
# ===========================================================================

@dataclass
class PlanStep:
    """Individual decomposed sub-task in an execution plan."""
    step_id: int
    objective: str
    target_tool: Optional[str] = None
    expected_output: str = ""


@dataclass
class ExecutionPlan:
    """Structured decomposition generated by the Planner Agent."""
    goal: str
    steps: List[PlanStep] = field(default_factory=list)
    strategy: str = ""


@dataclass
class CriticReview:
    """Auditing evaluation and critique generated by the Critic Agent."""
    approved: bool
    groundedness_score: float  # 0.0 - 100.0%
    objections: List[str] = field(default_factory=list)
    suggested_revisions: List[str] = field(default_factory=list)
    confidence: float = 1.0


@dataclass
class DebateRound:
    """Record of an individual iteration in the multi-agent consensus panel."""
    round_number: int
    plan: ExecutionPlan
    executor_synthesis: str
    tool_observations: List[Dict[str, Any]]
    critic_review: CriticReview
    duration_seconds: float = 0.0


@dataclass
class ConsensusResult:
    """Final output generated by the collaborative multi-agent consensus panel."""
    goal: str
    final_answer: str
    consensus_approved: bool
    total_rounds: int
    debate_history: List[DebateRound] = field(default_factory=list)
    total_latency_seconds: float = 0.0
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_markdown(self) -> str:
        """Render complete debate trajectory and verified synthesis into Markdown."""
        lines = [
            "# Multi-Agent Collaborative Consensus Report",
            f"**Objective:** {self.goal}  ",
            f"**Consensus Status:** {'[APPROVED]' if self.consensus_approved else '[CEILING REACHED (Partially Verified)]'}  ",
            f"**Total Debate Rounds:** {self.total_rounds}  ",
            f"**Total Latency:** {self.total_latency_seconds:.2f}s  ",
            "",
            "## Verified Final Synthesis",
            "",
            self.final_answer,
            "",
            "## Peer Review & Debate Trajectory",
            "",
        ]

        for r in self.debate_history:
            lines.extend([
                f"### Round {r.round_number}",
                f"**Planner Strategy:** {r.plan.strategy}",
                "",
                "**Planned Tasks:**",
            ])
            for s in r.plan.steps:
                lines.append(f"- `[{s.step_id}]` {s.objective} (Tool: `{s.target_tool or 'internal'}`)")
            lines.extend([
                "",
                f"**Critic Review:** {'Approved' if r.critic_review.approved else 'Revisions Requested'} "
                f"(Groundedness Score: {r.critic_review.groundedness_score:.1f}%)",
            ])
            if r.critic_review.objections:
                lines.append("**Critic Objections:**")
                for obj in r.critic_review.objections:
                    lines.append(f"- [!] {obj}")
            if r.critic_review.suggested_revisions:
                lines.append("**Suggested Revisions:**")
                for rev in r.critic_review.suggested_revisions:
                    lines.append(f"- [*] {rev}")
            lines.append("")

        return "\n".join(lines)


